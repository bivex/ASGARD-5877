def verify_candidate(name: str, desc: str, expr: z3.BitVecRef) -> Tuple[bool, bool, str]:
    simp = z3.simplify(expr)
    simp_str = str(simp)
    collapses = (simp_str == "0")

    s = z3.Solver()
    s.set("timeout", 2000)
    s.add(expr != 0)
    chk = s.check()
    is_unsat = (chk == z3.unsat)

    return is_unsat, collapses, simp_str

def synthesize_catalog() -> List[DiscoveredIdentity]:
    catalog = []
    print("=" * 75)
    print("🔬 ASGARD-5877: Synthesizing & Proving CFF Opaque Predicates (Z3 BitVec64)")
    print("=" * 75)

    for name, desc, expr in CANDIDATE_TEMPLATES:
        is_sound, collapses, simp_str = verify_candidate(name, desc, expr)
        status = "PASSED" if is_sound and not collapses else "REJECTED"
        print(f"[{status:<8}] {name:<24}: Sound(Z3)={is_sound!s:<5} | Collapse={collapses!s:<5}")
        if is_sound and not collapses:
            catalog.append(DiscoveredIdentity(name, desc, expr, simp_str))

    print(f"\n✅ Synthesized {len(catalog)} provably sound, non-collapsing opaque predicate identities.")
    return catalog

