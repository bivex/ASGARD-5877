let bytes_of_lanes (l0, l1) =
  let b = Array.make 16 0 in
  for i = 0 to 7 do
    b.(i) <- Int64.to_int (Int64.logand (Int64.shift_right_logical l0 (i * 8)) 0xFFL);
    b.(i + 8) <- Int64.to_int (Int64.logand (Int64.shift_right_logical l1 (i * 8)) 0xFFL);
  done;
  b

let lanes_of_bytes (b : int array) =
  let l0 = ref 0L in
  let l1 = ref 0L in
  for i = 0 to 7 do
    l0 := Int64.logor !l0 (Int64.shift_left (Int64.of_int (b.(i) land 0xFF)) (i * 8));
    l1 := Int64.logor !l1 (Int64.shift_left (Int64.of_int (b.(i + 8) land 0xFF)) (i * 8));
  done;
  (!l0, !l1)

let shift_rows (s : int array) =
  let r = Array.make 16 0 in
  r.(0)  <- s.(0);  r.(4)  <- s.(4);  r.(8)  <- s.(8);  r.(12) <- s.(12);
  r.(1)  <- s.(5);  r.(5)  <- s.(9);  r.(9)  <- s.(13); r.(13) <- s.(1);
  r.(2)  <- s.(10); r.(6)  <- s.(14); r.(10) <- s.(2);  r.(14) <- s.(6);
  r.(3)  <- s.(15); r.(7)  <- s.(3);  r.(11) <- s.(7);  r.(15) <- s.(11);
  r

let inv_shift_rows (s : int array) =
