let sub_bytes (s : int array) =
  Array.map (fun b -> sbox.(b land 0xFF)) s

let inv_sub_bytes (s : int array) =
  Array.map (fun b -> inv_sbox.(b land 0xFF)) s

let xtime x =
  let x = x land 0xFF in
  let res = (x lsl 1) land 0xFF in
  if x land 0x80 <> 0 then res lxor 0x1B else res

let mul_gf a b =
  let res = ref 0 in
  let temp = ref a in
  let b = ref b in
  for _ = 0 to 7 do
    if !b land 1 <> 0 then res := !res lxor !temp;
    temp := xtime !temp;
    b := !b lsr 1
  done;
  !res

let mix_columns (s : int array) =
  let r = Array.make 16 0 in
  for c = 0 to 3 do
    let i = c * 4 in
    let s0 = s.(i) in
    let s1 = s.(i + 1) in
    let s2 = s.(i + 2) in
    let s3 = s.(i + 3) in
    r.(i)     <- xtime s0 lxor (xtime s1 lxor s1) lxor s2 lxor s3;
    r.(i + 1) <- s0 lxor xtime s1 lxor (xtime s2 lxor s2) lxor s3;
    r.(i + 2) <- s0 lxor s1 lxor xtime s2 lxor (xtime s3 lxor s3);
    r.(i + 3) <- (xtime s0 lxor s0) lxor s1 lxor s2 lxor xtime s3;
  done;
  r

let inv_mix_columns (s : int array) =
  let r = Array.make 16 0 in
  for c = 0 to 3 do
    let i = c * 4 in
    let s0 = s.(i) in
    let s1 = s.(i + 1) in
    let s2 = s.(i + 2) in
    let s3 = s.(i + 3) in
    r.(i)     <- mul_gf 0x0e s0 lxor mul_gf 0x0b s1 lxor mul_gf 0x0d s2 lxor mul_gf 0x09 s3;
    r.(i + 1) <- mul_gf 0x09 s0 lxor mul_gf 0x0e s1 lxor mul_gf 0x0b s2 lxor mul_gf 0x0d s3;
    r.(i + 2) <- mul_gf 0x0d s0 lxor mul_gf 0x09 s1 lxor mul_gf 0x0e s2 lxor mul_gf 0x0b s3;
    r.(i + 3) <- mul_gf 0x0b s0 lxor mul_gf 0x0d s1 lxor mul_gf 0x09 s2 lxor mul_gf 0x0e s3;
  done;
  r

let add_round_key (s : int array) (k : int array) =
  let r = Array.make 16 0 in
  for i = 0 to 15 do
    r.(i) <- (s.(i) land 0xFF) lxor (k.(i) land 0xFF)
  done;
  r

let aesenc state key =
  add_round_key (mix_columns (sub_bytes (shift_rows state))) key

let aesenclast state key =
  add_round_key (sub_bytes (shift_rows state)) key

let aesdec state key =
  add_round_key (inv_mix_columns (inv_sub_bytes (inv_shift_rows state))) key

let aesdeclast state key =
  add_round_key (inv_sub_bytes (inv_shift_rows state)) key

let aesimc state =
  inv_mix_columns state

let aeskeygenassist (src : int array) (rcon : int) =
  let r = Array.make 16 0 in
  let s0 = sbox.(src.(4) land 0xFF) in
  let s1 = sbox.(src.(5) land 0xFF) in
  let s2 = sbox.(src.(6) land 0xFF) in
  let s3 = sbox.(src.(7) land 0xFF) in
  r.(0) <- s0;
  r.(1) <- s1;
  r.(2) <- s2;
  r.(3) <- s3;
  r.(4) <- s1 lxor (rcon land 0xFF);
  r.(5) <- s2;
  r.(6) <- s3;
  r.(7) <- s0;
  let s4 = sbox.(src.(12) land 0xFF) in
  let s5 = sbox.(src.(13) land 0xFF) in
  let s6 = sbox.(src.(14) land 0xFF) in
  let s7 = sbox.(src.(15) land 0xFF) in
  r.(8)  <- s4;
  r.(9)  <- s5;
  r.(10) <- s6;
  r.(11) <- s7;
  r.(12) <- s5 lxor (rcon land 0xFF);
  r.(13) <- s6;
  r.(14) <- s7;
  r.(15) <- s4;
  r
